import 'package:directory_tree_bench_harness/harness.dart';

/// The implementations the report has columns for, in column order.
const List<String> knownImplementations = ['v1', 'v2'];

/// A benchmark record (one JSON line) plus the environment it ran in.
typedef BenchRecord = Map<String, Object?>;

/// The key that identifies a measurement across runs.
String recordKey(BenchRecord r) =>
    '${r['implementation']}|${r['shape']}|${r['size']}|${r['operation']}';

/// Merges [fresh] into [existing]: a fresh record replaces an existing one
/// with the same [recordKey]. The result is sorted for stable output.
List<BenchRecord> mergeRecords(
  List<BenchRecord> existing,
  List<BenchRecord> fresh,
) {
  final byKey = {for (final r in existing) recordKey(r): r};
  for (final r in fresh) {
    byKey[recordKey(r)] = r;
  }
  return byKey.values.toList()..sort(_compareRecords);
}

int _indexOr(List<String> order, Object? value) {
  final i = order.indexOf('$value');
  return i == -1 ? order.length : i;
}

int _compareRecords(BenchRecord a, BenchRecord b) {
  final shapes = [for (final s in WorkloadShape.values) s.name];
  int cmp(Object? x, Object? y) => '$x'.compareTo('$y');
  final byShape = _indexOr(shapes, a['shape']) - _indexOr(shapes, b['shape']);
  if (byShape != 0) return byShape;
  final bySize = (a['size']! as int) - (b['size']! as int);
  if (bySize != 0) return bySize;
  final byOp =
      _indexOr(standardOperations, a['operation']) -
      _indexOr(standardOperations, b['operation']);
  if (byOp != 0) return byOp;
  final byImpl =
      _indexOr(knownImplementations, a['implementation']) -
      _indexOr(knownImplementations, b['implementation']);
  if (byImpl != 0) return byImpl;
  return cmp(a['implementation'], b['implementation']);
}

/// Formats milliseconds with precision that suits the magnitude.
String formatMs(num ms) {
  if (ms >= 100) return _thousands(ms.round());
  if (ms >= 1) return ms.toStringAsFixed(2);
  return ms.toStringAsFixed(3);
}

String _thousands(int n) {
  final s = n.toString();
  final out = StringBuffer();
  for (var i = 0; i < s.length; i++) {
    if (i > 0 && (s.length - i) % 3 == 0) out.write(',');
    out.write(s[i]);
  }
  return out.toString();
}

/// The table cell for one record's median.
String medianCell(BenchRecord? r) {
  if (r == null) return '';
  final median = r['median_ms'];
  if (median is num) return formatMs(median);
  final timeout = r['timeout_ms'];
  if (timeout is num) {
    final blockedBy = r['blocked_by'];
    return blockedBy != null
        ? 'timeout (blocked by $blockedBy)'
        : '> ${formatMs(timeout)} (timeout)';
  }
  if (r.containsKey('error')) {
    final blockedBy = r['blocked_by'];
    return blockedBy != null ? 'error (blocked by $blockedBy)' : 'error';
  }
  return '';
}

/// The speedup of [v2] over [v1] (v1 median / v2 median).
String speedupCell(BenchRecord? v1, BenchRecord? v2) {
  final v2Median = v2?['median_ms'];
  if (v1 == null || v2Median is! num || v2Median <= 0) return '';
  final v1Median = v1['median_ms'];
  if (v1Median is num) return '${_ratio(v1Median / v2Median)}x';
  final timeout = v1['timeout_ms'];
  if (timeout is num) return '> ${_ratio(timeout / v2Median)}x';
  return '';
}

String _ratio(double r) =>
    r >= 100 ? _thousands(r.round()) : r.toStringAsFixed(r >= 10 ? 1 : 2);

/// One machine/SDK combination the records were measured on.
String environmentOf(BenchRecord r) =>
    '${r['machine'] ?? 'unknown machine'}; ${r['os'] ?? 'unknown OS'}; '
    '${r['dart'] ?? 'unknown Dart'}';

/// Renders RESULTS.md.
String renderMarkdown(
  List<BenchRecord> records, {
  required List<Workload> workloads,
  required DateTime generatedAt,
}) {
  final b = StringBuffer()
    ..writeln('# Benchmark results')
    ..writeln()
    ..writeln(
      'Generated by `benchmark/runner` on '
      '${generatedAt.toUtc().toIso8601String().substring(0, 10)}. '
      'See `benchmark/README.md` for what each operation measures. '
      'Raw records: `benchmark/results.jsonl`.',
    )
    ..writeln();

  final envs = {for (final r in records) environmentOf(r)};
  b.writeln('## Environment');
  b.writeln();
  for (final env in envs) {
    b.writeln('- $env');
  }
  if (envs.length > 1) {
    b
      ..writeln()
      ..writeln(
        '> Records come from more than one environment; compare columns '
        'only when they share one (see the details table).',
      );
  }
  final settings = {
    for (final r in records)
      'warm-up ${r['warmup']}, timed runs ${r['runs']}, '
          'budget ${formatMs(r['budget_ms']! as num)} ms per step',
  };
  b
    ..writeln()
    ..writeln(
      'Executables: AOT (`dart compile exe`). Settings: '
      '${settings.join(' / ')}.',
    )
    ..writeln();

  // Main comparison table.
  final groups = <String, Map<String, BenchRecord>>{};
  for (final r in records) {
    final key = '${r['shape']}|${r['size']}|${r['operation']}';
    (groups[key] ??= {})['${r['implementation']}'] = r;
  }
  b
    ..writeln('## Results')
    ..writeln()
    ..writeln(
      'Median wall time per operation in milliseconds. '
      'Speedup = v1 median / v2 median.',
    )
    ..writeln()
    ..writeln(
      '| operation | shape | size | v1 median (ms) | v2 median (ms) | speedup |',
    )
    ..writeln('|---|---|---:|---:|---:|---:|');
  for (final entry in groups.entries) {
    final any = entry.value.values.first;
    final v1 = entry.value['v1'];
    final v2 = entry.value['v2'];
    b.writeln(
      '| ${any['operation']} | ${any['shape']} | ${_thousands(any['size']! as int)} '
      '| ${medianCell(v1)} | ${medianCell(v2)} | ${speedupCell(v1, v2)} |',
    );
  }

  // Fingerprint consistency.
  final fingerprints = <String, Set<Object?>>{};
  for (final r in records) {
    if (r['fingerprint'] == null) continue;
    (fingerprints['${r['shape']} ${r['size']}'] ??= {}).add(r['fingerprint']);
  }
  final mismatched = [
    for (final e in fingerprints.entries)
      if (e.value.length > 1) e.key,
  ];
  if (mismatched.isNotEmpty) {
    b
      ..writeln()
      ..writeln(
        '> Warning: workload fingerprints differ between records for '
        '${mismatched.join(', ')}; those comparisons are not like for like.',
      );
  }

  // Workloads.
  b
    ..writeln()
    ..writeln('## Workloads')
    ..writeln()
    ..writeln(
      '| shape | size | folders | max file depth | toggle target '
      '(files below) | filter query (matching files) | fingerprint |',
    )
    ..writeln('|---|---:|---:|---:|---|---|---|');
  for (final w in workloads) {
    b.writeln(
      '| ${w.shape.name} | ${_thousands(w.size)} | ${_thousands(w.folderCount)} '
      '| ${w.maxFileDepth} | `${w.toggleTarget}` '
      '(${_thousands(w.toggleTargetFileCount)}) '
      '| `${w.filterQuery}` (${_thousands(w.filterMatchCount)}) '
      '| `${w.fingerprint}` |',
    );
  }

  // Details.
  const known = {
    'implementation', 'shape', 'size', 'operation', 'runs', 'warmup', //
    'budget_ms', 'seed', 'fingerprint', 'median_ms', 'min_ms', 'max_ms',
    'machine', 'os', 'dart', 'timeout_ms', 'timeout_phase', 'blocked_by',
    'completed_runs', 'error',
  };
  b
    ..writeln()
    ..writeln('## Details')
    ..writeln()
    ..writeln(
      '| implementation | operation | shape | size | median | min | max '
      '| result counts / failure |',
    )
    ..writeln('|---|---|---|---:|---:|---:|---:|---|');
  for (final r in records) {
    String ms(String key) => r[key] is num ? formatMs(r[key]! as num) : '';
    final counts = [
      for (final e in r.entries)
        if (!known.contains(e.key)) '${e.key} ${e.value}',
    ];
    final failure = [
      if (r['timeout_phase'] != null) 'timeout in ${r['timeout_phase']}',
      if (r['completed_runs'] != null) '${r['completed_runs']} runs done',
      if (r['blocked_by'] != null) 'blocked by ${r['blocked_by']}',
      if (r['error'] != null) 'error: ${_escape('${r['error']}')}',
    ];
    b.writeln(
      '| ${r['implementation']} | ${r['operation']} | ${r['shape']} '
      '| ${_thousands(r['size']! as int)} | ${ms('median_ms')} | ${ms('min_ms')} '
      '| ${ms('max_ms')} | ${[...counts, ...failure].join(', ')} |',
    );
  }
  return b.toString();
}

String _escape(String s) {
  final oneLine = s.replaceAll('|', r'\|').replaceAll('\n', ' ');
  return oneLine.length > 200 ? '${oneLine.substring(0, 200)}...' : oneLine;
}
